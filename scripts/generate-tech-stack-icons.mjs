import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const packageEntry = require.resolve("tech-stack-icons");
const packageSource = await readFile(packageEntry, "utf8");
const marker = "var f=";
const objectStart = packageSource.indexOf(marker) + marker.length;
const objectEnd = packageSource.indexOf(";var h=f", objectStart);

if (objectStart === marker.length - 1 || objectEnd === -1) {
  throw new Error("Could not find the tech-stack-icons catalog.");
}

const catalog = Function(
  `"use strict"; return (${packageSource.slice(objectStart, objectEnd)});`,
)();
const iconNames = [
  "android",
  "azure",
  "bootstrap5",
  "c#",
  "c++",
  "claude",
  "cloudflare",
  "css3",
  "docker",
  "git",
  "github",
  "html5",
  "ionic",
  "java",
  "js",
  "linux",
  "microsoft",
  "mongodb",
  "netcore",
  "nextjs",
  "nginx",
  "openai",
  "pandas",
  "postgresql",
  "pytest",
  "python",
  "raspberrypi",
  "react",
  "spring",
  "tailwindcss",
  "techstackicons",
  "twilio",
  "typescript",
  "windows11",
];

const icons = Object.fromEntries(
  iconNames.map((name) => {
    const svg = catalog[name]?.svg?.light;
    if (!svg) throw new Error(`Missing light icon variant: ${name}`);
    return [name, svg];
  }),
);
const generatedSource = `// Generated by scripts/generate-tech-stack-icons.mjs.
// Source: https://www.tech-stack-icons.com/ (MIT).
// Do not edit this file directly.

export const techStackIconSvgs = ${JSON.stringify(icons, null, 2)} as const;

export type TechStackIconName = keyof typeof techStackIconSvgs;
`;

await writeFile(
  new URL("../lib/tech-stack-icons.generated.ts", import.meta.url),
  generatedSource,
);
